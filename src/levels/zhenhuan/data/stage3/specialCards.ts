/** 登门开场文本：随疑点、遗物、出宫档位不同。 */
export function dengmenOpenText(doubt: number, relics: number, exitTier: ExitTier | null): string {
  const tier = exitTier === 2 || exitTier === 3 ? exitTier : 1;
  const score = doubt + relics;
  const fill = (text: string) => text.replace("{why}", YIHUA.dengmenOpen.why[tier]!);
  if (score <= 0) return fill(YIHUA.dengmenOpen.none);
  const base = score <= 2 ? YIHUA.dengmenOpen.light : score <= 4 ? YIHUA.dengmenOpen.mid : YIHUA.dengmenOpen.heavy;
  return fill(base) + (relics > 0 ? YIHUA.dengmenOpen.relic : "") + (tier !== 1 ? YIHUA.dengmenOpen.notGraceful[tier]! : "");
}

/** 登门收尾：零疑点 / 打够 / 险胜（被废出宫必为险胜）。 */
export function dengmenCloseText(kind: "none" | "done" | "narrow", exitTier: ExitTier | null): string {
  const tier = exitTier === 2 || exitTier === 3 ? exitTier : 1;
  if (kind === "narrow") return tier === 3 ? YIHUA.dengmenNarrowFeichu : YIHUA.dengmenNarrow;
  if (kind === "none") return tier === 3 ? YIHUA.dengmenNoneDoneFeichu : tier === 2 ? YIHUA.dengmenNoneDoneQuan : YIHUA.dengmenNoneDone;
  return tier === 2 ? YIHUA.dengmenDoneQuan : YIHUA.dengmenDone;
}

